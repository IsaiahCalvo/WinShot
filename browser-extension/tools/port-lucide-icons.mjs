// Copies the Lucide icons the extension uses into src/lucide.js.
//   npm pack lucide-static@0.469.0 && tar -xzf lucide-static-0.469.0.tgz
//   node browser-extension/tools/port-lucide-icons.mjs package/icons
// Lucide is ISC-licensed (https://lucide.dev/license).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const NAMES = [
  "copy", "printer", "square-arrow-out-up-right", "history", "settings", "download",
  "info", "panel-right-open", "panel-right-close", "chevron-down", "scan", "x", "file-text", "image-down"
];
const source = process.argv[2];
if (!source) throw new Error("Pass the lucide-static icons folder.");
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "lucide.js");
const entries = NAMES.map((name) => {
  const raw = fs.readFileSync(path.join(source, `${name}.svg`), "utf8");
  const inner = raw.replace(/<!--[\s\S]*?-->/g, "").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>[\s\S]*$/, "")
    .replace(/\s*\n\s*/g, "").trim();
  const svg = `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;
  return `  ${JSON.stringify(name)}: ${JSON.stringify(svg)}`;
});
fs.writeFileSync(out, `// Generated by tools/port-lucide-icons.mjs from lucide-static 0.469.0 (ISC license,
// https://lucide.dev/license). Do not edit by hand.
export const LUCIDE = Object.freeze({
${entries.join(",\n")}
});
`);
console.log(`Wrote ${NAMES.length} icons to ${out}`);
